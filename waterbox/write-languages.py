def main():
    en = json.load(open(os.path.join(LANG, "en.json"), encoding="utf-8"))["texts"]
    missing = [k for k in en if k not in T]
    extra = [k for k in T if k not in en]
    if missing or extra:
        sys.exit("write-languages: no translations for %s; translations of no English key: %s" % (missing, extra))
    for code in MACHINE:
        texts = {}
        for key in sorted(en):
            text = T[key].get(code)
            if text is None:
                sys.exit("write-languages: %s has no %s text" % (key, code))
            texts[key] = text.replace("{M}", MACHINE[code])
        with open(os.path.join(LANG, code + ".json"), "w", encoding="utf-8") as f:
            json.dump({"texts": texts}, f, indent="\t", ensure_ascii=False)
            f.write("\n")
    print("write-languages: %d keys in %d languages" % (len(en), len(MACHINE) + 1))


if __name__ == "__main__":
    main()
